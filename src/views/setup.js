/**
 * views/setup.js — Screen 1 (plan §5): notes in (F1/F2), syllabus or
 * auto-detect (F5), hours (F7), Build button, model chip, ⚙, demo button,
 * import (F25), progress copy + Cancel, and the no-key inline error state.
 */
import { ROUTES, DEFAULTS } from '../contracts.js';

const STAGES = ['Reading notes', 'Mapping topics', 'Checking coverage', 'Preparing first lessons'];

function readText(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(String(reader.result || ''));
    reader.onerror = () => reject(new Error('Could not read ' + file.name));
    reader.readAsText(file);
  });
}

export async function render(container, ctx) {
  const { h, state, actions } = ctx;

  container.appendChild(h('div', { class: 'page-head' }, [
    h('h1', { class: 'page-title' }, [h('span', { class: 'title-mark', 'aria-hidden': 'true', text: '▲ ' }), 'Vertex · exam-ready notes']),
    h('p', { class: 'page-sub', text: 'Paste your messy notes and syllabus. Get a prioritized plan, missed-the-lecture lessons with computed examples, and a one-page sheet.' }),
  ]));

  /* ---- demo + resume card ---- */
  const demoCard = h('section', { class: 'card demo-card', 'aria-labelledby': 'demo-heading' });
  demoCard.appendChild(h('h2', { class: 'card-title', id: 'demo-heading', text: 'New here?' }));
  demoCard.appendChild(h('p', {
    class: 'muted',
    text: "Demo notebook: generated by Vertex's pipeline on sample notes with " + DEFAULTS.modelBharatcode + " and saved, so you can try it without a key.",
  }));
  const demoBtn = h('button', { type: 'button', class: 'btn btn-accent btn-lg', id: 'btn-demo', text: '▶ Try the demo notebook' });
  demoBtn.addEventListener('click', () => actions.tryDemo());
  demoCard.appendChild(demoBtn);

  const importRow = h('div', { class: 'import-row' }, [
    h('label', { class: 'file-btn', for: 'setup-import' }, 'Import notebook JSON'),
    h('input', { class: 'file-input', type: 'file', id: 'setup-import', accept: '.json,application/json', 'aria-label': 'Import a Vertex notebook JSON file (F25)' }),
  ]);
  demoCard.appendChild(importRow);

  if (state.notebook) {
    const resume = h('p', { class: 'resume-line' }, [
      h('button', { type: 'button', class: 'btn btn-ghost btn-sm', id: 'btn-resume', text: 'Continue: open “' + (state.notebook.title || 'your crash course') + '”' }),
    ]);
    resume.querySelector('#btn-resume').addEventListener('click', () => ctx.navigate(ROUTES.MAP));
    demoCard.appendChild(resume);
  }
  container.appendChild(demoCard);

  /* ---- build form card ---- */
  const form = h('section', { class: 'card build-card', 'aria-labelledby': 'build-heading' });
  form.appendChild(h('h2', { class: 'card-title', id: 'build-heading', text: 'Build your crash course' }));

  // 1 — notes (F1) + upload (F2)
  const notes = h('textarea', {
    id: 'setup-notes', class: 'text-input notes-box', rows: '8', spellcheck: 'false',
    'aria-label': 'Your notes', placeholder: 'Paste your lecture notes here — shorthand, half-derivations, skipped lines and all.',
  });
  const uploadInput = h('input', { type: 'file', id: 'setup-upload', accept: '.txt,.md,text/plain,text/markdown', 'aria-label': 'Upload a .txt or .md notes file (F2)' });
  const uploadName = h('span', { class: 'file-name muted', id: 'upload-name', text: '' });
  uploadInput.addEventListener('change', async (e) => {
    const f = e.target.files && e.target.files[0];
    if (!f) return;
    try {
      notes.value = await readText(f);
      uploadName.textContent = f.name + ' loaded';
      ctx.toast('Notes loaded from ' + f.name, 'good');
    } catch (err) {
      console.warn('setup.js: file read failed —', err.message);
      ctx.toast('Could not read that file.', 'error');
    }
  });
  form.appendChild(h('div', { class: 'step' }, [
    h('label', { class: 'step-label', for: 'setup-notes' }, [h('span', { class: 'step-num', text: '1' }), 'Your notes']),
    notes,
    h('div', { class: 'file-row' }, [h('label', { class: 'file-btn', for: 'setup-upload' }, 'Upload .txt / .md'), uploadInput, uploadName]),
  ]));

  // 2 — syllabus or auto-detect (F5)
  const syllabus = h('textarea', {
    id: 'setup-syllabus', class: 'text-input syllabus-box', rows: '4', spellcheck: 'false',
    'aria-label': 'Syllabus topics', placeholder: 'One topic per line, e.g.:\nNewton’s method\nQuasi-Newton / BFGS\nGram–Schmidt',
  });
  const detect = h('input', { type: 'checkbox', id: 'setup-detect' });
  detect.addEventListener('change', () => {
    syllabus.disabled = detect.checked;
    syllabus.classList.toggle('is-disabled', detect.checked);
  });
  form.appendChild(h('div', { class: 'step' }, [
    h('label', { class: 'step-label', for: 'setup-syllabus' }, [h('span', { class: 'step-num', text: '2' }), 'Syllabus topics']),
    syllabus,
    h('label', { class: 'check-row', for: 'setup-detect' }, [detect, h('span', { text: '( ) detect from notes instead' })]),
  ]));

  // 3 — hours (F7)
  const hours = h('input', {
    type: 'number', id: 'setup-hours', class: 'text-input hours-input',
    min: '0.5', max: '24', step: '0.5', 'aria-label': 'Hours you have to study',
    value: String(state.settings.hoursToStudy || DEFAULTS.hoursToStudy),
  });
  form.appendChild(h('div', { class: 'step' }, [
    h('label', { class: 'step-label', for: 'setup-hours' }, [h('span', { class: 'step-num', text: '3' }), 'I have']),
    h('div', { class: 'hours-row' }, [hours, h('span', { class: 'muted', text: 'hours to study' })]),
  ]));

  // actions row: build + model chip + gear
  const buildBtn = h('button', { type: 'button', class: 'btn btn-accent btn-lg', id: 'btn-build', text: 'Build my crash course' });
  const modelChip = h('button', {
    type: 'button', class: 'model-chip', id: 'model-chip',
    'aria-label': 'Model: ' + (state.settings.provider === 'demo' ? 'Demo' : 'BharatCode') + ' ' + state.settings.model + '. Open settings to change.',
  }, [
    'Model: ' + (state.settings.provider === 'demo' ? 'Demo' : 'BharatCode') + ' · ' + state.settings.model + ' ',
    h('span', { class: 'caret', 'aria-hidden': 'true', text: '▾' }),
  ]);
  const gear = h('button', { type: 'button', class: 'icon-btn', id: 'btn-gear', 'aria-label': 'Open settings' }, ['⚙']);
  buildBtn.addEventListener('click', () => {
    const notesRaw = notes.value.trim();
    if (!notesRaw) {
      state.setupError = { kind: 'empty_notes', message: 'Paste or upload your notes first — Vertex starts from your text.' };
      ctx.rerender();
      return;
    }
    const syllabusRaw = detect.checked ? '' : syllabus.value.trim();
    const hoursNum = Math.min(24, Math.max(0.5, Number(hours.value) || DEFAULTS.hoursToStudy));
    actions.buildCourse({ notesRaw, syllabusRaw, hours: hoursNum });
  });
  modelChip.addEventListener('click', actions.openSettings);
  gear.addEventListener('click', actions.openSettings);
  form.appendChild(h('div', { class: 'build-row' }, [buildBtn, modelChip, gear]));

  /* ---- inline error / empty state ---- */
  if (state.setupError) {
    const err = state.setupError;
    const box = h('div', { class: 'error-box', role: 'alert' });
    if (err.kind === 'no_key') {
      box.appendChild(h('p', { text: 'Add a free BharatCode key, or try the demo.' }));
      box.appendChild(h('p', { class: 'muted', text: 'Keys are free for students with a college email (.ac.in / .edu.in) at bharatcode.ai.' }));
      const keyBtn = h('button', { type: 'button', class: 'btn btn-ghost btn-sm', text: 'Open Settings ⚙' });
      keyBtn.addEventListener('click', actions.openSettings);
      const demoBtn2 = h('button', { type: 'button', class: 'btn btn-accent btn-sm', text: 'Try the demo' });
      demoBtn2.addEventListener('click', () => actions.tryDemo());
      box.appendChild(h('div', { class: 'btn-row' }, [keyBtn, demoBtn2]));
    } else {
      box.appendChild(h('p', { text: err.message || ctx.describeError(err) }));
      const retry = h('button', { type: 'button', class: 'btn btn-ghost btn-sm', text: 'Dismiss' });
      retry.addEventListener('click', () => { state.setupError = null; ctx.rerender(); });
      box.appendChild(retry);
    }
    form.appendChild(box);
  }

  /* ---- progress panel (never a blank screen) ---- */
  if (state.build && state.build.active) {
    const panel = h('div', { class: 'progress-panel', role: 'status', 'aria-live': 'polite' });
    panel.appendChild(h('h3', { class: 'progress-title', text: 'Building your crash course' }));
    const list = h('ol', { class: 'progress-steps' });
    STAGES.forEach((label, i) => {
      const st = state.build.stage;
      const cls = i < st ? 'step-done' : (i === st ? 'step-current' : 'step-pending');
      const marker = i < st ? '✓ ' : (i === st ? '● ' : '○ ');
      list.appendChild(h('li', { class: 'progress-step ' + cls }, [marker + label]));
    });
    panel.appendChild(list);
    const cancel = h('button', { type: 'button', class: 'btn btn-ghost btn-sm', id: 'btn-cancel-build', text: 'Cancel' });
    cancel.addEventListener('click', actions.cancelBuild);
    panel.appendChild(cancel);
    form.appendChild(panel);
    buildBtn.disabled = true;
  }

  container.appendChild(form);

  container.appendChild(h('p', { class: 'footnote muted', text: 'STEM-algorithmic topics get computed worked examples; other subjects still get the coverage map, lessons and sheet — without traces.' }));

  if (!(state.build && state.build.active)) notes.focus();
}
