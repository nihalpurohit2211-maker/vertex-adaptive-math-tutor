/**
 * views/map.js — Screen 2 (plan §5): "Plan: 3 h → 5 topics, ~2 h 45",
 * table rows with coverage chip (click → snippet drawer "why we think so"),
 * weight dots, rating buttons (real <button aria-pressed>), prereq ⚠ banner
 * (§6.5 rule), row tap → lesson, [Make my sheet].
 */
import { ROUTES } from '../contracts.js';

const CHIP = {
  covered: { dots: '●●○', label: 'Covered', cls: 'chip-covered' },
  thin: { dots: '●○○', label: 'Thin', cls: 'chip-thin' },
  not_found: { dots: '○○○', label: 'Not in your notes', cls: 'chip-none' },
};
const RATINGS = [['knew', 'Knew it'], ['kinda', 'Kind of'], ['lost', 'No idea']];

function fmtMinutes(m) {
  if (m >= 60) {
    const h = Math.floor(m / 60);
    const rest = m % 60;
    return rest ? h + ' h ' + rest : h + ' h';
  }
  return m + ' min';
}

export async function render(container, ctx) {
  const { h, state, actions } = ctx;
  const nb = state.notebook;

  if (!nb) {
    const card = h('div', { class: 'card empty-card' }, [
      h('h2', { class: 'card-title', text: 'No crash course yet.' }),
      h('p', { class: 'muted', text: 'Build one from your notes, or open the demo notebook — no key needed.' }),
    ]);
    const b1 = h('button', { type: 'button', class: 'btn btn-accent', text: 'Go to setup' });
    b1.addEventListener('click', () => ctx.navigate(ROUTES.SETUP));
    const b2 = h('button', { type: 'button', class: 'btn btn-ghost', text: '▶ Try the demo notebook' });
    b2.addEventListener('click', () => actions.tryDemo());
    card.appendChild(h('div', { class: 'btn-row' }, [b1, b2]));
    container.appendChild(card);
    return;
  }

  const plan = ctx.safePlan(nb);
  state.mapOrder = plan.ordered;
  const byId = new Map(nb.topics.map((t) => [t.id, t]));
  const budgetH = (nb.settings && nb.settings.hoursToStudy) || 3;
  const fitMin = plan.fits.reduce((s, id) => s + ((plan.minutesById && plan.minutesById[id]) || 0), 0);

  /* ---- header ---- */
  const head = h('div', { class: 'page-head' }, [
    h('h1', { class: 'page-title plan-title', text: 'Plan: ' + budgetH + ' h → ' + plan.fits.length + ' topics, ~' + fmtMinutes(fitMin) }),
  ]);
  if (plan.ifTime.length) {
    head.appendChild(h('p', { class: 'page-sub muted', text: '+ ' + plan.ifTime.length + ' more labeled “if time” — what’s left after the budget is filled.' }));
  }
  if (/demo/i.test(String(nb.id || '') + String(nb.title || ''))) {
    head.appendChild(h('p', {
      class: 'demo-note',
      text: "Demo notebook: generated by Vertex's pipeline on sample notes with qwen-3.8-27b and saved, so you can try it without a key. Add your own key in Settings ⚙ to use your notes.",
    }));
  }
  container.appendChild(head);

  /* ---- prefetch / build banner ---- */
  if (state.prefetch && state.prefetch.active) {
    const banner = h('div', { class: 'progress-panel', role: 'status', 'aria-live': 'polite' }, [
      h('span', { text: 'Preparing first lessons… (' + state.prefetch.done + ' of ' + state.prefetch.total + ' ready) — the rest generate on tap.' }),
    ]);
    const cancel = h('button', { type: 'button', class: 'btn btn-ghost btn-sm', text: 'Cancel' });
    cancel.addEventListener('click', actions.cancelBuild);
    banner.appendChild(cancel);
    container.appendChild(banner);
  }

  /* ---- snippet drawer (coverage "why we think so") ---- */
  const drawer = h('aside', { class: 'drawer card', id: 'coverage-drawer', hidden: true, role: 'complementary', 'aria-label': 'Matched note snippets' });
  const drawerTitle = h('h3', { class: 'drawer-title' });
  const drawerBody = h('div', { class: 'drawer-body' });
  const drawerClose = h('button', { type: 'button', class: 'icon-btn drawer-close', 'aria-label': 'Close snippets' }, ['×']);
  drawerClose.addEventListener('click', () => { drawer.hidden = true; });
  drawer.appendChild(drawerClose);
  drawer.appendChild(drawerTitle);
  drawer.appendChild(drawerBody);

  function openDrawer(topic) {
    const cov = topic.coverage || { status: 'not_found', chunkIds: [] };
    const chip = CHIP[cov.status] || CHIP.not_found;
    drawerTitle.textContent = 'Why we think “' + chip.label + '” for ' + topic.name;
    drawerBody.replaceChildren();
    const chunks = (nb.notes && nb.notes.chunks) || [];
    const hits = (cov.chunkIds || []).map((id) => chunks.find((c) => c.id === id)).filter(Boolean);
    if (!hits.length) {
      drawerBody.appendChild(h('p', { class: 'muted', text: 'Nothing in your notes matched this topic — Vertex will teach it from model knowledge, clearly labelled [Added by Vertex].' }));
    }
    for (const c of hits) {
      drawerBody.appendChild(h('blockquote', { class: 'snippet' }, [
        h('span', { class: 'snippet-id', text: '¶' + c.id }),
        h('p', { text: c.text }),
      ]));
    }
    drawer.hidden = false;
    drawer.scrollIntoView({ block: 'nearest' });
  }

  /* ---- plan table ---- */
  const wrap = h('div', { class: 'map-wrap' });
  const table = h('table', { class: 'map-table' });
  const thead = h('thead');
  const headRow = h('tr', {}, [
    h('th', { scope: 'col', text: '#' }),
    h('th', { scope: 'col', text: 'Topic' }),
    h('th', { scope: 'col', text: 'Notes' }),
    h('th', { scope: 'col', text: 'Weight' }),
    h('th', { scope: 'col', text: 'How well do you know it?' }),
  ]);
  thead.appendChild(headRow);
  table.appendChild(thead);
  const tbody = h('tbody');

  plan.ordered.forEach((id, idx) => {
    const topic = byId.get(id);
    if (!topic) return;
    const cov = topic.coverage || { status: 'not_found', chunkIds: [] };
    const chip = CHIP[cov.status] || CHIP.not_found;
    const fits = plan.fits.includes(id);

    const row = h('tr', {
      class: 'map-row' + (fits ? '' : ' row-ift'),
      tabindex: '0',
      'aria-label': 'Open lesson: ' + topic.name,
    });

    // # + minutes
    row.appendChild(h('td', { class: 'cell-num' }, [
      String(idx + 1),
      h('span', { class: 'minutes muted', text: (plan.minutesById[id] || 0) + ' min' }),
      fits ? null : h('span', { class: 'ift-tag', text: 'if time' }),
    ]));

    // topic name + lesson status + prereq banner
    const nameCell = h('td', { class: 'cell-topic' });
    const nameLine = h('span', { class: 'topic-name', text: topic.name });
    nameCell.appendChild(nameLine);
    const extras = [];
    if (topic.kind === 'conceptual') extras.push(h('span', { class: 'chip chip-ghost', title: 'Conceptual topic — no computed trace (Vertex is tuned for STEM-algorithmic examples).', text: 'words only' }));
    if (topic.lesson) extras.push(h('span', { class: 'lesson-ready ok', 'aria-label': 'lesson ready', text: '✓' }));
    else if (state.generating[id]) extras.push(h('span', { class: 'lesson-ready busy', 'aria-label': 'lesson generating', text: '…' }));
    else extras.push(h('span', { class: 'lesson-ready idle', 'aria-label': 'no lesson yet', text: '◦' }));
    nameCell.appendChild(h('span', { class: 'topic-extras' }, extras));

    for (const w of (plan.prereqWarnings || [])) {
      if (w.topicId !== id) continue;
      const pre = byId.get(w.prereqId);
      if (!pre) continue;
      const pos = plan.ordered.indexOf(w.prereqId) + 1;
      const warn = h('button', {
        type: 'button', class: 'prereq-banner',
        'aria-label': 'Prerequisite warning: ' + topic.name + ' builds on ' + pre.name + '. Start with it?',
      }, ['⚠ builds on #' + pos + ' ' + pre.name + ' — ', h('u', { text: 'Start with it?' })]);
      warn.addEventListener('click', (e) => {
        e.stopPropagation();
        ctx.navigate(ROUTES.LESSON_PREFIX + w.prereqId);
      });
      nameCell.appendChild(warn);
    }
    row.appendChild(nameCell);

    // coverage chip (click → drawer)
    const chipBtn = h('button', {
      type: 'button', class: 'coverage-chip ' + chip.cls,
      'aria-label': 'Coverage: ' + chip.label + '. Show why.', title: 'Why do we think this?',
    }, [h('span', { class: 'chip-dots', 'aria-hidden': 'true', text: chip.dots }), ' ' + chip.label]);
    chipBtn.addEventListener('click', (e) => { e.stopPropagation(); openDrawer(topic); });
    row.appendChild(h('td', { class: 'cell-coverage' }, [chipBtn]));

    // weight dots
    const w = topic.weight || 3;
    row.appendChild(h('td', { class: 'cell-weight' }, [
      h('span', { class: 'weight-dots', 'aria-hidden': 'true', text: '●'.repeat(w) + '○'.repeat(5 - w) }),
      h('span', { class: 'sr-only', text: 'Exam weight ' + w + ' of 5' }),
    ]));

    // rating buttons
    const ratingGroup = h('div', { class: 'rating-group', role: 'group', 'aria-label': 'How well do you know ' + topic.name + '?' });
    for (const [val, label] of RATINGS) {
      const on = topic.rating === val;
      const btn = h('button', {
        type: 'button', class: 'rate-btn rate-' + val + (on ? ' is-on' : ''),
        'aria-pressed': String(on), text: label,
      });
      btn.addEventListener('click', (e) => { e.stopPropagation(); actions.rateTopic(id, val); });
      ratingGroup.appendChild(btn);
    }
    row.appendChild(h('td', { class: 'cell-rating' }, [ratingGroup]));

    row.addEventListener('click', () => ctx.navigate(ROUTES.LESSON_PREFIX + id));
    row.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); ctx.navigate(ROUTES.LESSON_PREFIX + id); }
    });
    tbody.appendChild(row);
  });
  table.appendChild(tbody);
  wrap.appendChild(table);
  container.appendChild(wrap);
  container.appendChild(drawer);

  /* ---- bottom actions ---- */
  const sheetBtn = h('button', { type: 'button', class: 'btn btn-accent btn-lg', id: 'btn-sheet', text: 'Make my sheet' });
  sheetBtn.addEventListener('click', () => ctx.navigate(ROUTES.SHEET));
  const setupBtn = h('button', { type: 'button', class: 'btn btn-ghost', text: '← Back to setup' });
  setupBtn.addEventListener('click', () => ctx.navigate(ROUTES.SETUP));
  container.appendChild(h('div', { class: 'btn-row map-cta' }, [sheetBtn, setupBtn]));

  container.appendChild(h('p', { class: 'footnote muted', text: 'Tap a row to open its lesson. Ratings (Knew it / Kind of / No idea) reorder the plan — no quiz, no pen.' }));
}
